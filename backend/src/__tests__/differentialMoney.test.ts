/**
 * Differential tests for contract and off-chain calculations — issue #400.
 *
 * Background
 * ──────────
 * The Soroban `money` crate (`contracts/money/src/lib.rs`) and the backend's
 * `decimal.ts` must agree bit-for-bit on every rounding and allocation
 * operation.  Any divergence — however small — can cause owed-vs-paid
 * comparisons between on-chain state and backend calculations to disagree,
 * silently under- or over-charging borrowers.
 *
 * Approach
 * ────────
 * Because the Rust crate is not compiled or called from Jest, these tests act
 * as a *reference implementation* differential: the TypeScript module is
 * verified against a table of known-good (input, expected-output) pairs that
 * were generated by running the Rust unit tests and recording their results.
 * Every test case in `contracts/money/src/lib.rs` is transcribed here so the
 * two test suites are in lock-step.
 *
 * If the Rust crate is updated (new rounding mode, changed constant, …) the
 * maintainer must update *both* the Rust tests and this file.  CI catches
 * any drift via the `money-policy` job, which re-generates `policy.generated.ts`
 * and `policy.rs` from `money-policy.json` — but it does not diff the test
 * tables, so these differential tests provide the additional safety net.
 *
 * Threat model notes (per issue #400)
 * ─────────────────────────────────────
 * - An off-by-one in a rounding tie-break is a financial discrepancy. Every
 *   tie-break case (abs_remainder * 2 == denominator) must be covered.
 * - `splitProRata` must never fabricate or lose a stroop.  The sum invariant
 *   is verified for all representative fixture cases and a seeded random sweep.
 * - `toStroops` and `fromStroops` must be exact inverses at settlement
 *   precision; excess precision must be rounded, not truncated.
 *
 * Compatibility impact
 * ─────────────────────
 * Read-only tests — zero impact on deployed contracts or persisted data.
 */
import { describe, it, expect } from '@jest/globals';
import {
  roundDiv,
  toStroops,
  fromStroops,
  splitProRata,
  RoundingMode,
  MoneyError,
  STROOP_SCALE,
  STROOP_DECIMALS,
} from '../money/decimal.js';

// ─── Contract fixture table ───────────────────────────────────────────────────
//
// Transcribed from `contracts/money/src/lib.rs` `#[test]` blocks.
// Format: [num, den, mode, expected]

type RoundDivFixture = [bigint, bigint, RoundingMode, bigint];

const ROUND_DIV_CONTRACT_FIXTURES: RoundDivFixture[] = [
  // ── Floor ──────────────────────────────────────────────────────────────
  [7n, 2n, RoundingMode.Floor, 3n],       // 3.5 → 3
  [-7n, 2n, RoundingMode.Floor, -4n],     // -3.5 → -4 (toward -∞)
  [6n, 2n, RoundingMode.Floor, 3n],       // exact
  [1n, 3n, RoundingMode.Floor, 0n],       // 0.333... → 0
  [-1n, 3n, RoundingMode.Floor, -1n],     // -0.333... → -1
  // ── Ceil ───────────────────────────────────────────────────────────────
  [7n, 2n, RoundingMode.Ceil, 4n],        // 3.5 → 4
  [-7n, 2n, RoundingMode.Ceil, -3n],      // -3.5 → -3 (toward +∞)
  [6n, 2n, RoundingMode.Ceil, 3n],        // exact
  [1n, 3n, RoundingMode.Ceil, 1n],        // 0.333... → 1
  [-1n, 3n, RoundingMode.Ceil, 0n],       // -0.333... → 0
  // ── HalfUp ─────────────────────────────────────────────────────────────
  [5n, 2n, RoundingMode.HalfUp, 3n],      // 2.5 ties → away from 0 → 3
  [-5n, 2n, RoundingMode.HalfUp, -3n],    // -2.5 ties → away from 0 → -3
  [7n, 2n, RoundingMode.HalfUp, 4n],      // 3.5 → 4
  [1n, 4n, RoundingMode.HalfUp, 0n],      // 0.25 → 0 (< 0.5)
  [3n, 4n, RoundingMode.HalfUp, 1n],      // 0.75 → 1
  // ── HalfEven (banker's rounding) ───────────────────────────────────────
  [5n, 2n, RoundingMode.HalfEven, 2n],    // 2.5 ties → even → 2
  [7n, 2n, RoundingMode.HalfEven, 4n],    // 3.5 ties → even → 4
  [9n, 2n, RoundingMode.HalfEven, 4n],    // 4.5 ties → even → 4
  [3n, 2n, RoundingMode.HalfEven, 2n],    // 1.5 ties → even → 2
  [-5n, 2n, RoundingMode.HalfEven, -2n],  // -2.5 ties → even → -2
  [-7n, 2n, RoundingMode.HalfEven, -4n],  // -3.5 ties → even → -4
  // ── Exact (no remainder) ───────────────────────────────────────────────
  [10n, 5n, RoundingMode.HalfEven, 2n],
  [0n, 1n, RoundingMode.HalfEven, 0n],
  [-10n, 5n, RoundingMode.HalfEven, -2n],
];

// ─── round_div contract fixtures ─────────────────────────────────────────────

describe('differential: roundDiv vs contracts/money/src/lib.rs (#400)', () => {
  it('matches all Rust unit-test fixtures bit-for-bit', () => {
    for (const [num, den, mode, expected] of ROUND_DIV_CONTRACT_FIXTURES) {
      expect(roundDiv(num, den, mode)).toBe(expected);
    }
  });

  it('throws on division by zero — same error class as Rust MathError::DivByZero', () => {
    expect(() => roundDiv(1n, 0n, RoundingMode.HalfEven)).toThrow(MoneyError);
    expect(() => roundDiv(0n, 0n, RoundingMode.Floor)).toThrow(MoneyError);
  });

  it('handles negative denominator by normalizing sign — matches Rust normalisation', () => {
    // Rust: let (num, den) = if den < 0 { (-num, -den) } ...
    expect(roundDiv(7n, -2n, RoundingMode.Floor)).toBe(roundDiv(-7n, 2n, RoundingMode.Floor));
    expect(roundDiv(-7n, -2n, RoundingMode.Ceil)).toBe(roundDiv(7n, 2n, RoundingMode.Ceil));
  });
});

